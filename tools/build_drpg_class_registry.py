#!/usr/bin/env python3
"""DRPGPARTY1: the Disgaea RPG class registry (class id -> favourite weapon, potential type) for the evility runtime.

    python tools/build_drpg_class_registry.py [MASTERS_DIR] [--check]

Reads the JP client's `character` master (Disgaea Source/Disgaea RPG JP (Android), Unity MonoBehaviour.DataList,
read with UnityPy the way tools/census does) and drpg-leases.json, and writes d5lib/importers/drpg-class-registry.json:
one entry per imported class id -- the 146 bases' own class ids and the 89 costume class ids (a costume has the type
of its owner) -- with

    weapon     the character's `best_weapon_type` (the source's favourite weapon) as a D5 item category
               (DRPG 1 sword, 2 fist, 3 spear, 4 bow, 5 gun, 6 axe, 7 staff, 8 monster physical, 9 monster magic
               -> D5 category 2, 1, 3, 4, 5, 6, 7, 8, 9: the table drpg-evility-map/census.py WEAPON uses)
    potential  `m_potential_class_id` (1 King, 2 Pawn, 3 Rook, 4 Bishop, 5 Knight, 6 Queen; 0 = none)

The registry is the data behind the self_potential and party_weapons_distinct conditions (d5lib/evility.py class_table);
a pack that carries an evility needing decision D4 ships it under "classes" in patches/evilities/evilities.json.
Derived, reviewed data: the numbers are the source's, nothing is guessed; a character with no weapon or type in the
master is written with 0 for it (a class with both 0 is left out).
"""
import json
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parents[1]
IMP = KIT / "d5lib/importers"
OUT = IMP / "drpg-class-registry.json"
DEFAULT_MASTERS = Path("/Volumes/Data/Projects/D5/Disgaea Source/Disgaea RPG JP (Android)/extracted/sdcard/Android/data/"
                       "com.disgaearpg.forwardworks/files/assetbundle/masters")
WEAPON = {1: 2, 2: 1, 3: 3, 4: 4, 5: 5, 6: 6, 7: 7, 8: 8, 9: 9}          # DRPG weapon type -> D5 item category
POTENTIAL = {1: "King", 2: "Pawn", 3: "Rook", 4: "Bishop", 5: "Knight", 6: "Queen"}


def character_master(masters):
    import hashlib
    import UnityPy
    raw = (Path(masters) / "character").read_bytes()
    env = UnityPy.load(raw)
    rows = next(o for o in env.objects if o.type.name == "MonoBehaviour").parse_as_dict()["DataList"]
    return {r["id"]: r for r in rows}, hashlib.sha256(raw).hexdigest()


def build(masters):
    ch, sha = character_master(masters)
    lease = json.loads((IMP / "drpg-leases.json").read_text())
    base_of = {b["lease"]: int(b["lease"].split(":")[1]) for b in lease["bases"]}
    classes, names = {}, {}

    def add(class_id, base_id, name):
        c = ch[base_id]
        w = WEAPON.get(c["best_weapon_type"], 0)
        p = c["m_potential_class_id"] if c["m_potential_class_id"] in POTENTIAL else 0
        if not (w or p):
            return
        assert str(class_id) not in classes, class_id
        classes[str(class_id)] = {"weapon": w, "potential": p}
        names[str(class_id)] = name

    for b in lease["bases"]:
        add(b["class_id"], base_of[b["lease"]], b["name"])
    for c in lease["costumes"]:
        add(c["class_id"], base_of[c["owner"]], c["name"])
    classes = dict(sorted(classes.items(), key=lambda kv: int(kv[0])))
    return dict(
        schema="drpg-class-registry/1",
        source="generated by tools/build_drpg_class_registry.py from the JP client master `character` (best_weapon_type, "
               "m_potential_class_id) and drpg-leases.json (class ids of the bases and the costumes); read by "
               "d5lib/importers/drpg_evilities.py - never recomputed at build time",
        character_master_sha256=sha,
        weapon_drpg_to_d5_item_category={str(k): v for k, v in WEAPON.items()},
        potential_types={str(k): v for k, v in POTENTIAL.items()},
        counts=dict(classes=len(classes), bases=len(lease["bases"]), costumes=len(lease["costumes"]),
                    by_potential={POTENTIAL[p]: sum(1 for v in classes.values() if v["potential"] == p) for p in POTENTIAL},
                    by_weapon={str(w): sum(1 for v in classes.values() if v["weapon"] == w) for w in range(1, 10)}),
        classes=classes,
        names=names)


def main(argv):
    check = "--check" in argv
    args = [a for a in argv if not a.startswith("--")]
    doc = build(args[0] if args else DEFAULT_MASTERS)
    text = json.dumps(doc, ensure_ascii=False, indent=1) + "\n"
    if check:
        same = OUT.exists() and OUT.read_text() == text
        print("registry is current" if same else "registry differs from the masters")
        return 0 if same else 1
    OUT.write_text(text)
    print(json.dumps(doc["counts"], indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
