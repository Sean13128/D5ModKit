def cmd_name(cid: int) -> str:
    return NAMES[cid][0] if cid in NAMES else "cmd_%04x" % cid


class Var:
    """Variable reference operand (kind byte != 0)."""
    __slots__ = ("id", "kind")

    def __init__(self, vid: int, kind: int = 1):
        self.id = vid
        self.kind = kind

    def __eq__(self, o):
        return isinstance(o, Var) and o.id == self.id and o.kind == self.kind

    def __repr__(self):
        return "$%d" % self.id if self.kind == 1 else "$%d:%d" % (self.id, self.kind)


Operand = Union[int, Var]


def _enc_slot(v: Operand, size: int) -> bytes:
    if isinstance(v, Var):
        return bytes([v.kind]) + struct.pack("<H", v.id)
    return b"\0" + (int(v) & ((1 << (8 * size)) - 1)).to_bytes(size, "little")


def _dec_slot(code: bytes, p: int, size: int):
    kind = code[p]
    if kind:
        return Var(struct.unpack_from("<H", code, p + 1)[0], kind), p + 3
    return int.from_bytes(code[p + 1:p + 1 + size], "little"), p + 1 + size


class Cond:
    __slots__ = ("lhs", "op", "rhs")

    def __init__(self, lhs: Operand, op: int, rhs: Operand):
        self.lhs, self.op, self.rhs = lhs, op, rhs


class Ins:
    """Script instruction.
    args  : operand list (ints / Var) for normal commands; for call_event the event id followed by the
            call arguments; for set_var [raw, var_id, op, value]; for set_string [bytes].
    conds / logic / target : for `if` (target = the Ins execution skips to, or None = end of event).
    """
    __slots__ = ("cid", "args", "conds", "logic", "target", "_rel")

    def __init__(self, cid: int, args=None, conds=None, logic=None, target=None):
        self.cid = cid
        self.args = list(args or [])
        self.conds: List[Cond] = list(conds or [])
        self.logic: List[int] = list(logic or [])
        self.target: Optional["Ins"] = target
        self._rel = None

    @property
    def name(self):
        return cmd_name(self.cid)

    def encode(self, rel: int = 0) -> bytes:
        c = self.cid
        out = bytearray([c >> 8, c & 0xFF])
        if c in (0x0104, 0x0106):
            out += _enc_slot(self.args[0], 3)
            out += _enc_slot(len(self.args) - 1, 1)
            for a in self.args[1:]:
                out += _enc_slot(a, 4)
        elif c == 0x0140:
            out += struct.pack("<hB", rel, len(self.conds))
            for i, cd in enumerate(self.conds):
                out += _enc_slot(cd.lhs, 2) + bytes([cd.op]) + _enc_slot(cd.rhs, 2)
                if i < len(self.conds) - 1:
                    out.append(self.logic[i])
        elif c in (0x1400, 0x1410):
            raw, vid, op, val = self.args
            out += struct.pack("<BHB", raw, vid, op) + _enc_slot(val, 2)
        elif c == 0x6E20:
            s = self.args[0]
            out += bytes([len(s)]) + s
        else:
            sig = SIGS[c]
            if len(sig) != len(self.args):
                raise ValueError("%s expects %d operands, got %d" % (self.name, len(sig), len(self.args)))
            for a, size in zip(self.args, sig):
                out += _enc_slot(a, size)
        return bytes(out)

    def size(self) -> int:
        return len(self.encode(0))

    def __repr__(self):
        if self.cid == 0x0140:
            return "Ins(if %s)" % " ".join("%r%s%r" % (c.lhs, CMP_OPS.get(c.op, c.op), c.rhs) for c in self.conds)
        return "Ins(%s %s)" % (self.name, self.args)


def decode_ins(code: bytes, p: int):
    """Returns (Ins, next_pos, rel) - rel is the raw if-skip for 0x0140 (else None)."""
    cid = code[p] << 8 | code[p + 1]
    q = p + 2
    rel = None
    if cid in (0x0104, 0x0106):
        eid, q = _dec_slot(code, q, 3)
        n, q = _dec_slot(code, q, 1)
        if isinstance(n, Var):
            raise ValueError("call_event with variable arg count at %#x" % p)
        args = [eid]
        for _ in range(n):
            a, q = _dec_slot(code, q, 4)
            args.append(a)
        ins = Ins(cid, args)
    elif cid == 0x0140:
        rel, n = struct.unpack_from("<hB", code, q)
        q += 3
        conds, logic = [], []
        for i in range(n):
            lhs, q = _dec_slot(code, q, 2)
            op = code[q]
            q += 1
            rhs, q = _dec_slot(code, q, 2)
            conds.append(Cond(lhs, op, rhs))
            if i < n - 1:
                logic.append(code[q])
                q += 1
        ins = Ins(cid, conds=conds, logic=logic)
    elif cid in (0x1400, 0x1410):
        raw, vid, op = struct.unpack_from("<BHB", code, q)
        val, q = _dec_slot(code, q + 4, 2)
        ins = Ins(cid, [raw, vid, op, val])
    elif cid == 0x6E20:
        n = code[q]
        ins = Ins(cid, [bytes(code[q + 1:q + 1 + n])])
        q += 1 + n
    elif cid in SIGS:
        args = []
        for size in SIGS[cid]:
            a, q = _dec_slot(code, q, size)
            args.append(a)
        ins = Ins(cid, args)
    else:
        raise ValueError("unknown script command %04x at %#x" % (cid, p))
    return ins, q, rel


class Event:
    __slots__ = ("id", "code", "raw")

    def __init__(self, eid: int, code: Optional[List[Ins]] = None, raw: Optional[bytes] = None):
        self.id = eid
        self.code: List[Ins] = list(code or [])
        self.raw = raw      # set only when the block could not be disassembled (kept verbatim)

    def encode(self) -> bytes:
        if self.raw is not None:
            return self.raw
        pos, p = [], 0
        for ins in self.code:              # sizes do not depend on rel
            pos.append(p)
            p += ins.size()
        index = {id(i): k for k, i in enumerate(self.code)}
        out = bytearray()
        for k, ins in enumerate(self.code):
            rel = 0
            if ins.cid == 0x0140:
                if ins.target is None:
                    tpos = p
                elif id(ins.target) in index:
                    tpos = pos[index[id(ins.target)]]
                else:
                    raise ValueError("if target not in event %d" % self.id)
                rel = tpos - (pos[k] + 4)
            out += ins.encode(rel)
        return bytes(out)

    def __repr__(self):
        return "Event(%d, %d ins)" % (self.id, len(self.code))


def parse_event(eid: int, code: bytes, start: int, end: int) -> Event:
    items, p = [], start
    while p < end:
        ins, q, rel = decode_ins(code, p)
        items.append((p, ins, rel))
        p = q
    if p != end:
        raise ValueError("event %d overruns its block" % eid)
    at = {pp: ins for pp, ins, _ in items}
    for pp, ins, rel in items:
        if ins.cid == 0x0140:
            t = pp + 4 + rel
            if t == end:
                ins.target = None
            elif t in at:
                ins.target = at[t]
            else:
                raise ValueError("if target not on instruction boundary in event %d" % eid)
    return Event(eid, [i for _, i, _ in items])


class ScriptFile:
    def __init__(self):
        self.events: List[Event] = []

    @staticmethod
    def _looks_plain(b: bytes) -> bool:
        if len(b) < 8:
            return False
        n = struct.unpack_from("<I", b)[0]
        return 0 < n < 0x100000 and 4 + 8 * n <= len(b) and struct.unpack_from("<I", b, 4)[0] == 0

    @classmethod
    def from_bytes(cls, b: bytes, strict: bool = True, pause=None) -> "ScriptFile":
        """pause: called every 256 events (a background load lets the GUI thread have the interpreter)"""
        if not cls._looks_plain(b):
            b = crypt.decode(b)
            if not cls._looks_plain(b):
                raise ValueError("not a script.dat")
        n = struct.unpack_from("<I", b)[0]
        offs = struct.unpack_from("<%dI" % n, b, 4)
        ids = struct.unpack_from("<%dI" % n, b, 4 + 4 * n)
        code = b[4 + 8 * n:]
        if list(offs) != sorted(offs):
            raise ValueError("event offsets not ascending - unsupported layout")
        self = cls()
        ends = list(offs[1:]) + [len(code)]
        for k, (eid, o, e) in enumerate(zip(ids, offs, ends)):
            if pause is not None and not k & 255:
                pause()
            try:
                self.events.append(parse_event(eid, code, o, e))
            except (ValueError, IndexError, struct.error):
                if strict:
                    raise
                self.events.append(Event(eid, raw=bytes(code[o:e])))
        return self

    @classmethod
    def load(cls, path: str, strict: bool = True) -> "ScriptFile":
        with open(path, "rb") as f:
            return cls.from_bytes(f.read(), strict)

    def to_bytes(self) -> bytes:
        blobs = [e.encode() for e in self.events]
        offs, p = [], 0
        for bl in blobs:
            offs.append(p)
            p += len(bl)
        n = len(self.events)
        return (struct.pack("<I", n) + struct.pack("<%dI" % n, *offs)
                + struct.pack("<%dI" % n, *[e.id for e in self.events]) + b"".join(blobs))

    def save(self, path: str, obfuscate: bool = True):
        b = self.to_bytes()
        with open(path, "wb") as f:
            f.write(crypt.encode(b) if obfuscate else b)

    # ------------------------------------------------------------------ helpers
    def get(self, eid: int) -> Optional[Event]:
        for e in self.events:          # the game uses the first match as well
            if e.id == eid:
                return e
        return None

    def add_event(self, ev: Event) -> Event:
        if self.get(ev.id) is not None:
            raise ValueError("event id %d already exists (the game would use the first one)" % ev.id)
        self.events.append(ev)
        return ev

    def remove_event(self, eid: int):
        self.events = [e for e in self.events if e.id != eid]

    def references(self) -> Dict[int, List[int]]:
        """event id -> list of event ids it starts via spawn_event / call_event."""
        out = {}
        for e in self.events:
            refs = [i.args[0] for i in e.code if i.cid in (0x0100, 0x0104, 0x0106) and isinstance(i.args[0], int)]
            if refs:
                out[e.id] = refs
        return out

    # ------------------------------------------------------------------ text
    def disassemble(self, events=None, comments: bool = True) -> str:
        out = ["; script.dat disassembly (d5lib.script)"]
        for e in (self.events if events is None else events):
            out.extend(disassemble_event(e, comments))
        return "\n".join(out) + "\n"

    @classmethod
    def assemble(cls, text: str) -> "ScriptFile":
        self = cls()
        cur_lines: List[str] = []
        cur_id = None
        for ln in text.splitlines():
            s = ln.split(";", 1)[0].strip() if not ln.lstrip().startswith("set_string") else ln.strip()
            if not s:
                continue
            m = re.match(r"event\s+(\d+)(\s+raw\s+([0-9a-fA-F]*))?$", s)
            if m:
                if cur_id is not None:
                    self.events.append(assemble_event(cur_id, cur_lines))
                cur_id, cur_lines = int(m.group(1)), []
                if m.group(2):
                    self.events.append(Event(cur_id, raw=bytes.fromhex(m.group(3))))
                    cur_id = None
                continue
            cur_lines.append(s)
        if cur_id is not None:
            self.events.append(assemble_event(cur_id, cur_lines))
        return self


# ---------------------------------------------------------------------- text format
def _fmt(v: Operand, size: int = 2) -> str:
    if isinstance(v, Var):
        return repr(v)
    if size in (2, 4) and v >= 1 << (8 * size - 1):
        return str(v - (1 << (8 * size)))
    return str(v)


def _parse_operand(s: str) -> Operand:
    s = s.strip()
    if s.startswith("$"):
        if ":" in s:
            a, b = s[1:].split(":")
            return Var(int(a), int(b))
        return Var(int(s[1:]))
    return int(s, 0)


def disassemble_event(e: Event, comments: bool = True) -> List[str]:
    if e.raw is not None:
        return ["", "event %d raw %s" % (e.id, e.raw.hex())]
    out = ["", "event %d" % e.id]
    targets = {id(i.target): None for i in e.code if i.cid == 0x0140 and i.target is not None}
    labels = {}
    for k, ins in enumerate(e.code):
        if id(ins) in targets:
            labels[id(ins)] = "L%d" % k
    end_label = "END"
    depth = 0
    for k, ins in enumerate(e.code):
        if id(ins) in labels:
            out.append("  %s:" % labels[id(ins)])
        c = ins.cid
        if c in (0x0148, 0x0158):
            depth = max(0, depth - 1)
        ind = "    " + "  " * depth
        if c == 0x0140:
            terms = []
            for i, cd in enumerate(ins.conds):
                op = CMP_OPS.get(cd.op, "op#%d" % cd.op)
                terms.append("(%s %s %s)" % (_fmt(cd.lhs), op, _fmt(cd.rhs)))
                if i < len(ins.logic):
                    terms.append(LOGIC_OPS.get(ins.logic[i], "op#%d" % ins.logic[i]))
            tgt = labels[id(ins.target)] if ins.target is not None else end_label
            out.append("%sif %s else %s" % (ind, " ".join(terms), tgt))
            depth += 1
            continue
        if c in (0x0104, 0x0106):
            txt = ", ".join([_fmt(ins.args[0], 3)] + [_fmt(a, 4) for a in ins.args[1:]])
        elif c in (0x1400, 0x1410):
            raw, vid, op, val = ins.args
            txt = "%d, %d, %d, %s" % (raw, vid, op, _fmt(val))
        elif c == 0x6E20:
            txt = json.dumps(ins.args[0].decode("latin-1"))
        else:
            txt = ", ".join(_fmt(a, s) for a, s in zip(ins.args, SIGS[c]))
        line = "%s%s %s" % (ind, ins.name, txt) if txt else ind + ins.name
        out.append(line.rstrip())
        if c == 0x0150:
            depth += 1
    return out


def assemble_event(eid: int, lines: List[str]) -> Event:
    items = []          # (Ins, target label or None)
    label_at = {}
    for s in lines:
        if s.endswith(":") and re.match(r"^\w+:$", s):
            label_at[s[:-1]] = len(items)
            continue
        name, _, rest = s.partition(" ")
        rest = rest.strip()
        if name == "if":
            m = re.match(r"(.*)\s+else\s+(\w+)$", rest)
            body, lbl = m.group(1), m.group(2)
            toks = re.findall(r"\(([^)]*)\)|(\band\b|\bor\b|op#\d+)", body)
            conds, logic = [], []
            for term, lop in toks:
                if term:
                    a, op, b = term.split()
                    opc = CMP_BY_SYM[op] if op in CMP_BY_SYM else int(op[3:])
                    conds.append(Cond(_parse_operand(a), opc, _parse_operand(b)))
                else:
                    logic.append(LOGIC_BY_SYM[lop] if lop in LOGIC_BY_SYM else int(lop[3:]))
            items.append((Ins(0x0140, conds=conds, logic=logic), lbl))
            continue
        cid = MNEM[name] if name in MNEM else int(name[4:], 16)
        if cid == 0x6E20:
            items.append((Ins(cid, [json.loads(rest).encode("latin-1")]), None))
            continue
        args = [_parse_operand(x) for x in rest.split(",")] if rest else []
        items.append((Ins(cid, args), None))
    code = [i for i, _ in items]
    for ins, lbl in items:
        if lbl is not None:
            if lbl == "END":
                ins.target = None
            else:
                idx = label_at[lbl]
                ins.target = code[idx] if idx < len(code) else None
    return Event(eid, code)
